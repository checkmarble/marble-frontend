import { isCanonicalUuid } from '@app-builder/models/tracfin';
import { z } from 'zod/v4';

/**
 * Validators of the TRACFIN server functions. The backend refuses any unknown JSON member, even a
 * nested one, so every object that is forwarded is a `z.strictObject` listing the contract members
 * of `packages/marble-api/openapis/marblecore-api/tracfin.yml` and nothing else.
 */

const nonEmpty = z.string().min(1);
// The server compares these as strings: only the canonical lowercase form it returned is valid.
const canonicalUuid = z.string().refine(isCanonicalUuid, 'Expected a canonical lowercase UUID');

// ---- Document building blocks ----

export const tracfinFieldRefSchema = z.strictObject({
  parent_value_id: nonEmpty.optional(),
  value_id: nonEmpty.optional(),
  block_id: nonEmpty,
  field_id: nonEmpty,
});

export const tracfinReferenceSchema = z.strictObject({
  block_id: nonEmpty,
  person_block_id: nonEmpty.optional(),
});

export const tracfinPathStepSchema = z.strictObject({
  id: nonEmpty,
  parent_id: nonEmpty.optional(),
  link: nonEmpty.optional(),
  direction: z.enum(['forward', 'inverse']).optional(),
  table: nonEmpty,
  record_id: nonEmpty.optional(),
});

export const tracfinSelectionSchema = z.strictObject({
  mapping_id: nonEmpty,
  root: tracfinPathStepSchema,
  bindings: z.array(tracfinPathStepSchema).optional(),
  decision_id: canonicalUuid.optional(),
  historical_type: nonEmpty.optional(),
  snapshot_field: nonEmpty.optional(),
});

export const tracfinFieldInputSchema = z.strictObject({
  parent_value_id: nonEmpty.optional(),
  kind: z.enum(['text', 'boolean', 'decimal', 'reference']),
  text: z.string().optional(),
  boolean: z.boolean().optional(),
  // Exact decimal lexeme: a number would lose it.
  decimal: z.string().optional(),
  reference: tracfinReferenceSchema.optional(),
});

export const tracfinChangeInputSchema = z.strictObject({
  candidate_id: nonEmpty.optional(),
  mapping_version: nonEmpty.optional(),
  action: z.enum([
    'set_field',
    'clear_field',
    'add_block',
    'remove_block',
    'set_selection',
    'set_relation',
    'apply_prefill',
    'refresh_configuration',
  ]),
  field: tracfinFieldRefSchema.optional(),
  value: tracfinFieldInputSchema.optional(),
  block_id: nonEmpty.optional(),
  parent_block_id: nonEmpty.optional(),
  catalog_id: nonEmpty.optional(),
  selection: tracfinSelectionSchema.optional(),
  relation: tracfinReferenceSchema.optional(),
  source_file_id: canonicalUuid.optional(),
  proposal_id: nonEmpty.optional(),
});

// ---- Configuration ----

// The configuration screen submits what the administrator typed, blanks included: the backend owns
// the diagnostics (INVALID_MAPPING_ID, MISSING_SOURCE_CODE, ...), so strings are not constrained here.
const tracfinMappingSourceSchema = z.strictObject({
  unit_operation: z.boolean().optional(),
  kind: z.enum(['ingested', 'decision_snapshot', 'settings']),
  entity_type: z.enum(['Person', 'Company']).optional(),
  table: z.string().optional(),
  field: z.string().optional(),
  historical_type: z.string().optional(),
  path: z.array(tracfinPathStepSchema).optional(),
});

export const tracfinMappingSchema = z.strictObject({
  discriminator: z.strictObject({ field: z.string(), values: z.array(z.string()) }).optional(),
  id: z.string(),
  target_field: z.string(),
  source: tracfinMappingSourceSchema,
  codes: z.array(z.strictObject({ source: z.string(), target: z.string() })).optional(),
  unit: z.enum(['major', 'minor']).optional(),
  target_currency: z.string().optional(),
  currency: z.strictObject({ field: z.string().optional(), constant: z.string().optional() }).optional(),
});

export const tracfinSettingInputSchema = z.strictObject({
  // Only `field_id` is read: blocks, values and owners of attributes are generated by the server.
  field: z.strictObject({ field_id: nonEmpty }),
  value: tracfinFieldInputSchema,
});

/** The organization comes from the session, not from the client: the PUT payload is the body itself. */
export const tracfinConfigurationInputSchema = z.strictObject({
  expected_revision: z.number().int().min(0),
  settings: z.array(tracfinSettingInputSchema),
  mappings: z.array(tracfinMappingSchema),
});

// ---- Case payloads ----

const caseId = z.uuid();
const expectedRevision = z.number().int().min(1);

export const tracfinCaseInputSchema = z.strictObject({ caseId });

export const tracfinCreateDraftInputSchema = z.strictObject({
  caseId,
  body: z.strictObject({ declarant_is_actor: z.boolean() }),
});

export const tracfinPatchDraftInputSchema = z.strictObject({
  caseId,
  body: z.strictObject({
    expected_revision: expectedRevision,
    changes: z.array(tracfinChangeInputSchema).min(1),
  }),
});

export const tracfinRevisionInputSchema = z.strictObject({
  caseId,
  body: z.strictObject({ expected_revision: expectedRevision }),
});

export const tracfinNavigateInputSchema = z.strictObject({
  caseId,
  body: z.strictObject({
    selection: tracfinSelectionSchema,
    step_id: nonEmpty,
    cursor: z.string().min(1).max(4096).optional(),
    limit: z.number().int().min(1).max(100).optional(),
  }),
});
